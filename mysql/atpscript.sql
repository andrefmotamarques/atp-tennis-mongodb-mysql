use atp;
-- =====================================================================
-- atpscript.sql - Limpeza, modelo relacional e consultas (Trabalho ATP)
-- Pre-condicao: base de dados "atp" criada pelo dump atpdb.sql, com a tabela
-- "atpplayers" (dados exportados do MongoDB, sem transformacoes).
-- Correr: mysql -u <utilizador> -p < atpscript.sql
-- O script pode ser corrido mais do que uma vez (apaga e recria as tabelas que cria).
-- Nao depende de ficheiros externos: a tabela de paises vai incluida no script
-- (em vez de LOAD DATA do countries_net.csv, que exige local_infile ativo).
-- =====================================================================
SET NAMES utf8mb4;

DROP TABLE IF EXISTS game;
DROP TABLE IF EXISTS edition;
DROP TABLE IF EXISTS tournament;
DROP TABLE IF EXISTS player;
DROP TABLE IF EXISTS round_type;
DROP TABLE IF EXISTS ground;
DROP TABLE IF EXISTS country_alias;
DROP TABLE IF EXISTS country;
DROP TABLE IF EXISTS cleaning_log;

-- Registo das linhas analisadas/perdidas em cada passo (usado no relatorio)
CREATE TABLE cleaning_log (
  step_id     INT AUTO_INCREMENT PRIMARY KEY,
  step        VARCHAR(100) NOT NULL,
  description VARCHAR(255) NOT NULL,
  n_rows      INT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

INSERT INTO cleaning_log (step, description, n_rows)
SELECT 'atpplayers', 'Linhas importadas do MongoDB (tabela original)', COUNT(*) FROM atpplayers;

-- =====================================================================
-- 1. PAISES
-- country: lista ISO 3166-1 (mesma fonte do link do enunciado, datahub country-list)
-- country_alias: variantes de escrita encontradas nos dados -> pais
--   (ex.: "USA", "U.S.A.", "England", "Czechoslovakia", estados dos EUA "CA", cidades sem pais "Moscow").
--   As cidades sem pais foram mapeadas com a base de dados GeoNames (so quando a cidade nao e ambigua)
--   e as restantes a mao; cidades ambiguas (ex.: "San Juan", "Salem") ficam sem pais.
-- =====================================================================
CREATE TABLE country (
  country_id CHAR(2)      NOT NULL,
  name       VARCHAR(100) NOT NULL,
  PRIMARY KEY (country_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE country_alias (
  alias      VARCHAR(100) NOT NULL,
  country_id CHAR(2)      NOT NULL,
  PRIMARY KEY (alias),
  CONSTRAINT fk_alias_country FOREIGN KEY (country_id) REFERENCES country (country_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

