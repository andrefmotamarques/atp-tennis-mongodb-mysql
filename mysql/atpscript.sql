-- =====================================================================
-- 4. TORNEIOS
-- tournament: o torneio (ex.: Wimbledon), com indicacao de Grand Slam
-- edition: cada edicao (torneio + local + datas), com piso, premio e pais do local
-- =====================================================================
CREATE TABLE tournament (
  tournament_id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  name          VARCHAR(100) NOT NULL,
  is_grand_slam TINYINT(1)   NOT NULL DEFAULT 0,
  PRIMARY KEY (tournament_id),
  UNIQUE KEY uk_tournament_name (name),
  KEY idx_tournament_gs (is_grand_slam),
  CONSTRAINT ck_tournament_gs CHECK (is_grand_slam IN (0, 1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

INSERT INTO tournament (name)
SELECT TRIM(Tournament) FROM atpplayers
WHERE Tournament IS NOT NULL AND TRIM(Tournament) <> ''
GROUP BY TRIM(Tournament);

-- Grand Slams (nomes encontrados nos dados; exclui as "Preliminary Round")
UPDATE tournament
SET is_grand_slam = 1
WHERE name IN ('Australian Open', 'Australian Open-1', 'Australian Open-2', 'Australian Championships',
               'Roland Garros', 'Wimbledon', 'US Open');

CREATE TABLE edition (
  edition_id    INT UNSIGNED     NOT NULL AUTO_INCREMENT,
  tournament_id INT UNSIGNED     NOT NULL,
  location      VARCHAR(100)     NOT NULL,
  country_id    CHAR(2)          NULL,
  start_date    DATE             NULL,
  end_date      DATE             NULL,
  ground_id     TINYINT UNSIGNED NULL,
  prize         VARCHAR(20)      NULL,
  date_text     VARCHAR(30)      NOT NULL,   -- auxiliar para ligar os jogos; removida no fim
  PRIMARY KEY (edition_id),
  UNIQUE KEY uk_edition (tournament_id, location, date_text),
  KEY idx_edition_ground (ground_id),
  KEY idx_edition_country (country_id),
  CONSTRAINT fk_edition_tournament FOREIGN KEY (tournament_id) REFERENCES tournament (tournament_id),
  CONSTRAINT fk_edition_country FOREIGN KEY (country_id) REFERENCES country (country_id),
  CONSTRAINT fk_edition_ground FOREIGN KEY (ground_id) REFERENCES ground (ground_id),
  CONSTRAINT ck_edition_dates CHECK (end_date IS NULL OR start_date IS NULL OR end_date >= start_date)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- Datas: "2021.11.22 - 2021.12.05" (inicio - fim) ou apenas "1984.05.07" (inicio = fim)
-- Piso/premio: 1 edicao tem 2 pisos e 120 tem o premio escrito de 2 formas -> fica o MAX
-- 3 edicoes tem a data de fim anterior a de inicio (erro na origem) -> end_date = NULL
INSERT INTO edition (tournament_id, location, date_text, start_date, end_date, ground_id, prize)
SELECT y.tournament_id, y.location, y.date_text, y.d_start,
       CASE WHEN y.d_end >= y.d_start THEN y.d_end END,
       y.ground_id, y.prize
FROM (
SELECT t.tournament_id,
       x.location,
       x.date_text,
       CASE WHEN x.date_text REGEXP '^[0-9]{4}[.][0-9]{2}[.][0-9]{2}( - [0-9]{4}[.][0-9]{2}[.][0-9]{2})?$'
            THEN STR_TO_DATE(LEFT(x.date_text, 10), '%Y.%m.%d') END AS d_start,
       CASE WHEN x.date_text REGEXP '^[0-9]{4}[.][0-9]{2}[.][0-9]{2}( - [0-9]{4}[.][0-9]{2}[.][0-9]{2})?$'
            THEN STR_TO_DATE(RIGHT(x.date_text, 10), '%Y.%m.%d') END AS d_end,
       g.ground_id,
       x.prize
FROM (SELECT TRIM(Tournament)              AS tournament,
             TRIM(Location)                AS location,
             TRIM(Date)                    AS date_text,
             MAX(NULLIF(TRIM(Ground), '')) AS ground,
             MAX(NULLIF(TRIM(Prize), ''))  AS prize
      FROM atpplayers
      WHERE Tournament IS NOT NULL AND TRIM(Tournament) <> ''
        AND Location IS NOT NULL AND Date IS NOT NULL AND TRIM(Date) <> ''
      GROUP BY TRIM(Tournament), TRIM(Location), TRIM(Date)) x
JOIN tournament t ON t.name = x.tournament
LEFT JOIN ground g ON g.name = x.ground
) y;

-- Pais do local do torneio ("Paris, France" -> FR; "Spain" -> ES)
UPDATE edition e
JOIN country_alias a ON a.alias = TRIM(SUBSTRING_INDEX(e.location, ',', -1))
SET e.country_id = a.country_id;

UPDATE edition e
JOIN country_alias a ON a.alias = TRIM(SUBSTRING_INDEX(e.location, ',', 1))
SET e.country_id = a.country_id
WHERE e.country_id IS NULL;

