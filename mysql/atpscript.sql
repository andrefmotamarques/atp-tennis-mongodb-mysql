CREATE TABLE ground (
  ground_id TINYINT UNSIGNED NOT NULL AUTO_INCREMENT,
  name      VARCHAR(20)      NOT NULL,
  PRIMARY KEY (ground_id),
  UNIQUE KEY uk_ground_name (name)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

INSERT INTO ground (name)
SELECT TRIM(Ground) FROM atpplayers
WHERE Ground IS NOT NULL AND TRIM(Ground) <> ''
GROUP BY TRIM(Ground)
ORDER BY TRIM(Ground);

CREATE TABLE round_type (
  round_id      TINYINT UNSIGNED NOT NULL AUTO_INCREMENT,
  name          VARCHAR(30)      NOT NULL,
  stage_order   TINYINT UNSIGNED NOT NULL,
  is_qualifying TINYINT(1)       NOT NULL DEFAULT 0,
  PRIMARY KEY (round_id),
  UNIQUE KEY uk_round_name (name),
  CONSTRAINT ck_round_qualifying CHECK (is_qualifying IN (0, 1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

INSERT INTO round_type (name, stage_order, is_qualifying)
SELECT r.name,
       CASE r.name
         WHEN '1st Round Qualifying' THEN 1
         WHEN '2nd Round Qualifying' THEN 2
         WHEN '3rd Round Qualifying' THEN 3
         WHEN 'Round of 128'         THEN 4
         WHEN 'Round of 64'          THEN 5
         WHEN 'Round of 32'          THEN 6
         WHEN 'Round of 16'          THEN 7
         WHEN 'Round Robin'          THEN 8
         WHEN 'Quarter-Finals'       THEN 9
         WHEN 'Semi-Finals'          THEN 10
         WHEN '3rd/4th Place Match'  THEN 11
         WHEN 'Olympic Bronze'       THEN 11
         WHEN 'Finals'               THEN 12
         ELSE 0
       END,
       CASE WHEN r.name LIKE '%Qualifying%' THEN 1 ELSE 0 END
FROM (SELECT TRIM(Round) AS name FROM atpplayers
      WHERE Round IS NOT NULL AND TRIM(Round) <> ''
      GROUP BY TRIM(Round)) r
ORDER BY 2;

-- =====================================================================
-- 3. JOGADORES
-- Chave: codigo ATP (PlayerId), porque ha nomes repetidos para jogadores diferentes.
-- Altura fora de 150-220 cm (ex.: 0, 3, 15, 510) -> NULL.
-- Hand "Right-Handed, Two-Handed Backhand" -> hand = Right-Handed, backhand = Two-Handed
-- =====================================================================
CREATE TABLE player (
  player_id  VARCHAR(10)       NOT NULL,
  name       VARCHAR(100)      NOT NULL,
  birthplace VARCHAR(100)      NULL,
  country_id CHAR(2)           NULL,
  height_cm  SMALLINT UNSIGNED NULL,
  hand       VARCHAR(15)       NULL,
  backhand   VARCHAR(15)       NULL,
  PRIMARY KEY (player_id),
  KEY idx_player_country (country_id),
  KEY idx_player_hand (hand),
  CONSTRAINT fk_player_country FOREIGN KEY (country_id) REFERENCES country (country_id),
  CONSTRAINT ck_player_height CHECK (height_cm IS NULL OR height_cm BETWEEN 150 AND 220),
  CONSTRAINT ck_player_hand CHECK (hand IS NULL OR hand IN ('Right-Handed', 'Left-Handed', 'Ambidextrous')),
  CONSTRAINT ck_player_backhand CHECK (backhand IS NULL OR backhand IN ('One-Handed', 'Two-Handed'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

INSERT INTO player (player_id, name, birthplace, height_cm, hand, backhand)
SELECT x.player_id,
       x.name,
       x.birthplace,
       CASE WHEN x.height REGEXP '^[0-9]{1,3}$' AND CAST(x.height AS UNSIGNED) BETWEEN 150 AND 220
            THEN CAST(x.height AS UNSIGNED) END,
       CASE WHEN TRIM(SUBSTRING_INDEX(x.hand, ',', 1)) IN ('Right-Handed', 'Left-Handed', 'Ambidextrous')
            THEN TRIM(SUBSTRING_INDEX(x.hand, ',', 1)) END,
       CASE TRIM(SUBSTRING_INDEX(x.hand, ',', -1))
            WHEN 'One-Handed Backhand' THEN 'One-Handed'
            WHEN 'Two-Handed Backhand' THEN 'Two-Handed' END
FROM (SELECT TRIM(PlayerId)                   AS player_id,
             MAX(TRIM(PlayerName))            AS name,
             MAX(NULLIF(TRIM(Born), ''))      AS birthplace,
             MAX(NULLIF(TRIM(Height), ''))    AS height,
             MAX(NULLIF(TRIM(Hand), ''))      AS hand
      FROM atpplayers
      WHERE PlayerId IS NOT NULL AND TRIM(PlayerId) <> ''
      GROUP BY TRIM(PlayerId)) x;

-- Pais do jogador: 1a tentativa pela ultima parte do local de nascimento ("Belgrade, Serbia" -> Serbia)
UPDATE player p
JOIN country_alias a ON a.alias = TRIM(SUBSTRING_INDEX(p.birthplace, ',', -1))
SET p.country_id = a.country_id
WHERE p.birthplace IS NOT NULL;

-- 2a tentativa pela primeira parte (casos so com cidade, ex.: "Moscow")
UPDATE player p
JOIN country_alias a ON a.alias = TRIM(SUBSTRING_INDEX(p.birthplace, ',', 1))
SET p.country_id = a.country_id
WHERE p.birthplace IS NOT NULL AND p.country_id IS NULL;

