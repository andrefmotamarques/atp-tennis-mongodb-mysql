-- =====================================================================
-- 6. CONSULTAS
-- Notas comuns:
--   - % de vitorias = vitorias / jogos disputados * 100 (walkovers nao contam, como na ATP)
--   - nas consultas 2 e 3 so entram jogadores com pelo menos 25 vitorias
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1) Por pais: numero de jogadores, numero de torneios e numero de rondas
--    jogadores: jogadores nascidos no pais
--    torneios: edicoes de torneios realizadas no pais
--    rondas: rondas que os jogadores do pais avancaram (= jogos ganhos, inclui walkovers)
-- ---------------------------------------------------------------------
SELECT c.name                      AS country,
       COALESCE(pl.n_players, 0)   AS players,
       COALESCE(ed.n_tournaments, 0) AS tournaments,
       COALESCE(rd.n_rounds, 0)    AS rounds
FROM country c
LEFT JOIN (SELECT country_id, COUNT(*) AS n_players
           FROM player WHERE country_id IS NOT NULL GROUP BY country_id) pl
       ON pl.country_id = c.country_id
LEFT JOIN (SELECT country_id, COUNT(*) AS n_tournaments
           FROM edition WHERE country_id IS NOT NULL GROUP BY country_id) ed
       ON ed.country_id = c.country_id
LEFT JOIN (SELECT p.country_id, COUNT(*) AS n_rounds
           FROM game g JOIN player p ON p.player_id = g.player_id
           WHERE g.result = 'W' AND p.country_id IS NOT NULL
           GROUP BY p.country_id) rd
       ON rd.country_id = c.country_id
WHERE pl.n_players IS NOT NULL OR ed.n_tournaments IS NOT NULL
ORDER BY players DESC, tournaments DESC, country;

-- ---------------------------------------------------------------------
-- 2) Top 10 jogadores por % de vitorias (minimo 25 vitorias)
--    (agrega primeiro os jogos e so depois junta o nome: muito mais rapido)
-- ---------------------------------------------------------------------
SELECT p.name                             AS player,
       x.wins,
       x.games,
       ROUND(100 * x.wins / x.games, 2)   AS win_pct
FROM (SELECT player_id,
             SUM(result = 'W') AS wins,
             COUNT(*)          AS games
      FROM game
      WHERE is_walkover = 0
      GROUP BY player_id
      HAVING SUM(result = 'W') >= 25) x
JOIN player p ON p.player_id = x.player_id
ORDER BY win_pct DESC, x.wins DESC
LIMIT 10;

-- ---------------------------------------------------------------------
-- 3) Top 10 esquerdinos por % de vitorias em jogos de Grand Slam
--    (quadro principal: rondas de qualificacao excluidas; minimo 25 vitorias em Grand Slams)
-- ---------------------------------------------------------------------
SELECT p.name                                AS player,
       x.gs_wins,
       x.gs_games,
       ROUND(100 * x.gs_wins / x.gs_games, 2) AS gs_win_pct
FROM (SELECT g.player_id,
             SUM(g.result = 'W') AS gs_wins,
             COUNT(*)            AS gs_games
      FROM game g
      JOIN edition e    ON e.edition_id = g.edition_id
      JOIN tournament t ON t.tournament_id = e.tournament_id
      JOIN round_type r ON r.round_id = g.round_id
      WHERE t.is_grand_slam = 1
        AND r.is_qualifying = 0
        AND g.is_walkover = 0
        AND g.player_id IN (SELECT player_id FROM player WHERE hand = 'Left-Handed')
      GROUP BY g.player_id
      HAVING SUM(g.result = 'W') >= 25) x
JOIN player p ON p.player_id = x.player_id
ORDER BY gs_win_pct DESC, x.gs_wins DESC
LIMIT 10;

-- ---------------------------------------------------------------------
-- 4) Top 5 jogadores com mais vitorias em piso duro (Hard)
-- ---------------------------------------------------------------------
SELECT p.name AS player,
       x.hard_wins
FROM (SELECT g.player_id,
             COUNT(*) AS hard_wins
      FROM game g
      JOIN edition e ON e.edition_id = g.edition_id
      JOIN ground gr ON gr.ground_id = e.ground_id
      WHERE gr.name = 'Hard'
        AND g.result = 'W'
        AND g.is_walkover = 0
      GROUP BY g.player_id) x
JOIN player p ON p.player_id = x.player_id
ORDER BY x.hard_wins DESC, p.name
LIMIT 5;
