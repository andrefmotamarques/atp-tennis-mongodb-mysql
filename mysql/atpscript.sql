UNION ALL
SELECT 'edition', 'Edicoes sem pais identificado (ex.: local "TBA")', COUNT(*) FROM edition WHERE country_id IS NULL
UNION ALL
SELECT 'edition', 'Edicoes sem piso (NULL)', COUNT(*) FROM edition WHERE ground_id IS NULL
UNION ALL
SELECT 'edition', 'Edicoes com data de fim invalida (NULL)', COUNT(*) FROM edition WHERE end_date IS NULL;

-- =====================================================================
-- 5. JOGOS
-- Cada linha e um jogo visto do lado de um jogador (resultado W/L desse jogador).
-- Duplicados logicos (mesmo jogador, edicao, ronda e adversario) -> fica 1.
-- "(W/O)" = walkover (vitoria sem jogo) -> marcado em is_walkover.
-- =====================================================================
CREATE TABLE game (
  game_id       INT UNSIGNED      NOT NULL AUTO_INCREMENT,
  player_id     VARCHAR(10)       NOT NULL,
  edition_id    INT UNSIGNED      NOT NULL,
  round_id      TINYINT UNSIGNED  NOT NULL,
  opponent      VARCHAR(100)      NOT NULL,
  opponent_rank SMALLINT UNSIGNED NULL,
  result        CHAR(1)           NOT NULL,
  score         VARCHAR(30)       NULL,
  is_walkover   TINYINT(1)        NOT NULL DEFAULT 0,
  PRIMARY KEY (game_id),
  UNIQUE KEY uk_game (player_id, edition_id, round_id, opponent),
  KEY idx_game_player_result (player_id, result, is_walkover),
  KEY idx_game_edition (edition_id),
  KEY idx_game_round (round_id),
  CONSTRAINT fk_game_player FOREIGN KEY (player_id) REFERENCES player (player_id),
  CONSTRAINT fk_game_edition FOREIGN KEY (edition_id) REFERENCES edition (edition_id),
  CONSTRAINT fk_game_round FOREIGN KEY (round_id) REFERENCES round_type (round_id),
  CONSTRAINT ck_game_result CHECK (result IN ('W', 'L')),
  CONSTRAINT ck_game_walkover CHECK (is_walkover IN (0, 1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

INSERT INTO game (player_id, edition_id, round_id, opponent, opponent_rank, result, score, is_walkover)
SELECT TRIM(a.PlayerId),
       e.edition_id,
       r.round_id,
       TRIM(a.Opponent),
       MAX(CASE WHEN TRIM(a.OpponentRank) REGEXP '^[0-9]{1,5}$' THEN CAST(TRIM(a.OpponentRank) AS UNSIGNED) END),
       MAX(TRIM(a.WL)),
       MAX(NULLIF(TRIM(a.Score), '')),
       MAX(CASE WHEN TRIM(a.Score) = '(W/O)' THEN 1 ELSE 0 END)
FROM atpplayers a
JOIN tournament t ON t.name = TRIM(a.Tournament)
JOIN edition e    ON e.tournament_id = t.tournament_id
                 AND e.location = TRIM(a.Location)
                 AND e.date_text = TRIM(a.Date)
JOIN round_type r ON r.name = TRIM(a.Round)
JOIN player p     ON p.player_id = TRIM(a.PlayerId)
WHERE TRIM(a.WL) IN ('W', 'L')
  AND a.Opponent IS NOT NULL AND TRIM(a.Opponent) NOT IN ('', 'bye')
GROUP BY TRIM(a.PlayerId), e.edition_id, r.round_id, TRIM(a.Opponent);

